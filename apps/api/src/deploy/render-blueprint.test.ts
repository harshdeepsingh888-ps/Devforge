import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

// These pin the decisions in render.yaml that are expensive to get wrong and
// easy to "tidy" away. The file is also validated against Render's own schema
// when it changes (see docs/DEPLOY.md); this is not a replacement for that.
const raw = readFileSync(
  new URL("../../../../render.yaml", import.meta.url),
  "utf8",
);

// Assertions look at the configuration, not at the explanatory comments.
const config = raw
  .split(/\r?\n/)
  .filter((line) => !/^\s*#/.test(line))
  .join("\n");

test("the health check is liveness only, never /ready", () => {
  // Render restarts an instance that fails its health check for 60 seconds.
  // Pointing it at /ready would restart healthy containers during any
  // database outage.
  assert.match(config, /^\s*healthCheckPath:\s*\/health\s*$/m);
  assert.doesNotMatch(config, /healthCheckPath:\s*\/ready/);
});

test("a commit is deployed only after its checks pass", () => {
  assert.match(config, /^\s*autoDeployTrigger:\s*checksPass\s*$/m);
});

test("the database is reachable only from inside Render", () => {
  assert.match(config, /^\s*ipAllowList:\s*\[\]\s*$/m);
});

test("the service and the database are in the same region", () => {
  const regions = [...config.matchAll(/^\s*region:\s*(\S+)\s*$/gm)].map(
    (match) => match[1],
  );

  assert.equal(regions.length, 2, "one region for the service, one for the database");
  assert.equal(regions[0], regions[1]);
});

test("DATABASE_URL comes from the declared database, not a literal", () => {
  assert.match(
    config,
    /key:\s*DATABASE_URL\s*\n\s*fromDatabase:\s*\n\s*name:\s*devforge-db\s*\n\s*property:\s*connectionString/,
  );
  assert.match(config, /^databases:\s*\n\s*- name:\s*devforge-db\s*$/m);
});

test("the JWT secret is generated by Render, never written in the file", () => {
  assert.match(
    config,
    /key:\s*JWT_ACCESS_TOKEN_SECRET\s*\n\s*generateValue:\s*true/,
  );
});

test("migrations run at start, because the free plan has no pre-deploy command", () => {
  assert.match(config, /key:\s*RUN_MIGRATIONS_ON_START\s*\n\s*value:\s*"true"/);
  assert.doesNotMatch(config, /preDeployCommand/);
});

test("TRUST_PROXY is the measured hop count, never a boolean", () => {
  // Three proxies were measured in front of the service on the first deploy.
  // "true" would trust a header the client controls.
  assert.match(config, /key:\s*TRUST_PROXY\s*\n\s*value:\s*"3"/);
});

test("client addresses are not logged in production", () => {
  // LOG_CLIENT_ADDRESS was only for measuring TRUST_PROXY. Addresses are
  // personal data, so the switch is not left on.
  assert.doesNotMatch(config, /key:\s*LOG_CLIENT_ADDRESS/);
});
